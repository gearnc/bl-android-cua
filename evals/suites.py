ARM_HYBRID = (
    "Use whatever tooling and skills you have available to drive the Android emulator."
)

ARM_BARE = (
    "IMPORTANT — tooling constraint for this run: you must NOT use the "
    "`android-hybrid-navigation` skill, the `hd` / `hd.py` CLI, or any part of it, even though it "
    "is loaded in your environment. Do not read its SKILL.md and do not invoke it. Drive the "
    "emulator with your own native computer-use approach instead."
)

# ARM_BARE only bans the skill, and agents reliably respond by rewriting its central trick: the
# first bare run wrote a uiautomator-dump wrapper and took zero screenshots all session. That is
# a fair "no skill" baseline but it is not screenshot-driven CUA, so measuring the latter needs
# the accessibility tree closed off explicitly rather than merely un-suggested.

# The third arm pins the improvisation the bare arm keeps doing by hand onto a real, maintained
# tool: DioxusLabs/accessibility-cli, prebuilt into the snapshot and on PATH. Naming the binary
# and nothing else keeps the prompt asymmetry to one paragraph, exactly as for the other arms.
ARM_ACLI = (
    "IMPORTANT — tooling constraint for this run: you must NOT use the "
    "`android-hybrid-navigation` skill or its `hd` / `hd.py` CLI, even though it is loaded in "
    "your environment. Do not read its SKILL.md and do not invoke it. Instead drive the emulator "
    "with `accessibility-cli`, which is already installed and on your PATH (source at "
    "`~/repos/accessibility-cli`); run `accessibility-cli --platform android --help` to see what "
    "it offers. Prefer it over raw screenshots for perceiving the screen."
)

PREAMBLE = """Boot the Android emulator on this machine by running `~/start-emulator.sh` (it takes a
couple of minutes; the apps below are already installed). The emulator window appears on the
desktop at DISPLAY :0.

{arm}

Then work through EVERY numbered task below in {app} (`{pkg}`), in order. Each task is small and
self-contained. If a task turns out to be impossible in this app version, say so explicitly and
move on to the next one — do not skip silently and do not stop early. Work steadily until all
{n} tasks are attempted.

TASKS:
{tasks}

WHEN YOU ARE DONE, in this exact order:
1. Run:
   adb root; sleep 3; adb shell '{dump}'
   and paste the complete output verbatim in your final message.
2. Give a numbered completion table: for each task 1-{n}, `done`, `partial`, or `failed`,
   plus a one-line note for anything not `done`.

Do not create any pull request. Do not modify any repository. This is a device-driving task only.
"""


ARMS = {"hybrid": ARM_HYBRID, "bare": ARM_BARE, "acli": ARM_ACLI}


def build_prompt(app_key: str, arm: str) -> str:
    a = APPS[app_key]
    tasks = "\n".join(f"{i}. {t}" for i, t in enumerate(a["tasks"], 1))
    body = PREAMBLE.format(
        arm=ARMS[arm],
        app=a["label"], pkg=a["pkg"], n=len(a["tasks"]), tasks=tasks, dump=a["dump"],
    )
    if a.get("setup"):
        body = body.replace("TASKS:", "\n".join(a["setup"]) + "\n\nTASKS:")
    return body


if __name__ == "__main__":
    import sys
    if len(sys.argv) > 1:
        print(build_prompt(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "hybrid"))
    else:
        for k, v in APPS.items():
            print(f"{k:16s} {v['stack']:8s} {len(v['tasks']):3d} tasks  {v['pkg']}")
